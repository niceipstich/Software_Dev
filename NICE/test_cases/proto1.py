from dataclasses import dataclass, field
from enum import Enum
from typing import Optional

# ---- Reserved keywords (add the rest here) ----
RESERVED_KEYWORDS = {
    "module",
    "Design",
}

class Direction(Enum):
    INPUT = "input"
    OUTPUT = "output"


@dataclass
class Port:
    name: str
    direction: Direction
    width: int
    default: Optional[int] = None


@dataclass
class Interface:
    name: str
    ports: list[Port] = field(default_factory=list)

    def port(self, name, direction, width, default=None):
        self.ports.append(Port(name, direction, width, default))
        return self


@dataclass
class Connection:
    """kind is 'net' (connect a <-> b) or 'expose_as' (promote to module boundary)."""
    kind: str
    interfaces: tuple


@dataclass
class Instance:
    module: "Module"
    name: str
    connections: list[Connection] = field(default_factory=list)

    def connect(self, *interfaces, net=False, expose_as=False):
        if net:
            self.connections.append(Connection("net", interfaces))
        if expose_as:
            self.connections.append(Connection("expose_as", interfaces))
        return self


@dataclass
class Module:
    name: str
    interfaces: dict[str, Interface] = field(default_factory=dict)
    instances: dict[str, Instance] = field(default_factory=dict)

    def interface(self, name) -> Interface:
        ifce = self.interfaces[name] = Interface(name)
        return ifce

    def instance(self, module: "Module", name: str) -> Instance:
        inst = self.instances[name] = Instance(module, name)
        return inst


# ---------------------------------------------------------------- mod1
mod1 = Module("mod1")
mod1.interface("ifce1") \
    .port("a", Direction.INPUT, width=4) \
    .port("b", Direction.OUTPUT, width=4)

# ---------------------------------------------------------------- mod2
mod2 = Module("mod2")
mod2.interface("ifce2") \
    .port("b", Direction.OUTPUT, width=4) \
    .port("a", Direction.INPUT, width=4)
mod2.interface("ifce3") \
    .port("c", Direction.OUTPUT, width=4, default=0x0)

# -------------------------------------------------------------- Design
design = Module("Design")

# Explicit initialization of an interface that the tool does not
# generate on its own.
design.interface("ifce3") \
    .port("c", Direction.OUTPUT, width=4, default=0x0)

# Instance declarations. Connectivity is defined at the instance level,
# not generated by the tool, so it is declared explicitly.
A = design.instance(mod1, "A")
A.connect("ifce1", "ifce2", net=True)

B = design.instance(mod2, "B")
B.connect("ifce1", "ifce2", net=True)
B.connect("ifce3", expose_as=True)


if __name__ == "__main__":
    for inst in design.instances.values():
        print(f"{inst.name} ({inst.module.name})")
        for c in inst.connections:
            print(f"  {c.kind}: {', '.join(c.interfaces)}")